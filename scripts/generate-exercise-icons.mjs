// Generates src/components/ExerciseIcon.tsx from scripts/exercise-catalogue.json.
// Icon sources: @bryllim/workout-guide frame-1 artwork (CC BY-SA 4.0) for
// "pack" rows, and the white-line SVGs in src/assets/exercises/ for "svg"
// rows (hand-made originals plus generated stick-figure poses for
// free-exercise-db entries, whose data is public domain / Unlicense).
import {readFile, writeFile} from 'node:fs/promises';

const catalogue = JSON.parse(await readFile(new URL('./exercise-catalogue.json', import.meta.url), 'utf8'));
const camel = slug => slug.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^([0-9])/, 'n$1');
const imports = new Map(); // asset path -> variable
const varFor = (kind, key) => {
  const path = kind === 'pack' ? `@bryllim/workout-guide/assets/${key}/frame-1.png` : `../assets/exercises/${key}.svg`;
  if (!imports.has(path)) imports.set(path, `${camel(key)}${kind === 'pack' ? 'Img' : 'Svg'}`);
  return imports.get(path);
};
const entries = catalogue.map(row => ` '${row.id}':${varFor(row.icon.type, row.icon.type === 'pack' ? row.icon.slug : row.icon.file)},`);
const lines = [
  '// Generated by scripts/generate-exercise-icons.mjs from scripts/exercise-catalogue.json. Do not edit by hand.',
  ...[...imports].map(([path, name]) => `import ${name} from '${path}';`),
  '',
  'const icons:Record<string,string>={',
  ...entries,
  '};',
  '',
  'export function ExerciseIcon({exerciseId}:{exerciseId:string}){',
  ' const src=icons[exerciseId];',
  ' return src?<img className="exercise-icon" src={src} alt="" aria-hidden="true"/>:null;',
  '}',
  '',
];
await writeFile(new URL('../src/components/ExerciseIcon.tsx', import.meta.url), lines.join('\n'));
console.log(`Wrote ExerciseIcon.tsx with ${entries.length} exercises and ${imports.size} icon assets.`);
